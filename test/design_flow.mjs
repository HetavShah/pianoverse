// Walk through the step flow as in the design and screenshot every screen.
import { chromium } from 'playwright';
import { mkdirSync } from 'node:fs';
const OUT = 'test/out/design'; mkdirSync(OUT, { recursive: true });
const CLIP = process.env.CLIP ?? '/home/claude/sample15a.webm';
const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium-1243/chrome-linux64/chrome', args: ['--enable-unsafe-webgpu', '--use-webgpu-adapter=swiftshader', '--enable-features=Vulkan', '--use-vulkan=swiftshader', '--disable-vulkan-surface', '--autoplay-policy=no-user-gesture-required'] });
const page = await b.newPage({ viewport: { width: 1440, height: 900 } });
page.on('pageerror', (e) => console.log('[pageerror]', e.message));
page.on('console', (m) => { if (m.type() === 'error' && !m.text().includes('404')) console.log('[console]', m.text()); });
await page.addInitScript(() => { window.__pvHeadless = true; });
await page.goto('http://localhost:4173/'); await page.waitForTimeout(800);
await page.screenshot({ path: `${OUT}/0-home-empty.png` });
await page.click('.row-actions >> text=New project');
await page.waitForTimeout(300);
await page.screenshot({ path: `${OUT}/1-import-empty.png` });
await page.setInputFiles('.file-card .actions input[type=file]', CLIP);
await page.waitForFunction(() => !!window.pianoverseProject, null, { timeout: 20000 });
await page.waitForTimeout(800);
await page.screenshot({ path: `${OUT}/2-import-filled.png` });
await page.click('text=Continue to video');
await page.waitForTimeout(800);
await page.screenshot({ path: `${OUT}/2b-video.png` });
await page.click('text=Continue to audio');
await page.waitForTimeout(800);
await page.setInputFiles('.title-row input[type=file]', 'test/fixtures/interstellar-shifted.mid');
await page.waitForFunction(() => window.pianoverseProject?.noteSource?.confidence !== undefined, null, { timeout: 60000 });
await page.waitForTimeout(1500);
await page.$eval('.page-foot', () => {});
const v = await page.$('video');
await page.evaluate(() => { const v = document.querySelector('video'); v.currentTime = 6; });
await page.waitForTimeout(1200);
await page.screenshot({ path: `${OUT}/3-notes.png` });
console.log('banner:', await page.$eval('.banner', (e) => e.textContent.replace(/\s+/g, ' ').trim()));
