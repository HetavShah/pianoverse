await page.waitForTimeout(1500);
await page.screenshot({ path: `${OUT}/5-style.png` });
await page.click('text=Shorts guides');
await page.click('.seg >> text=Original');
await page.waitForTimeout(500);
await page.screenshot({ path: `${OUT}/6-style-original-guides.png` });
await page.click('.brand');
await page.waitForTimeout(1500);
await page.screenshot({ path: `${OUT}/7-home-recent.png` });
console.log('recent cards:', await page.$$eval('.project-card .name', (els) => els.map((e) => e.textContent)));
// reopen it
await page.click('.project-card .thumb');
await page.waitForTimeout(1000);
console.log('reopened at step:', await page.$eval('.step-btn.on', (e) => e.textContent), '| video issue card:', !!(await page.$('.file-card.warn')));
await page.screenshot({ path: `${OUT}/8-reopened.png` });
