// Colours and Notes panels: colour modes, gradients, colour wheel, solid / texture material.
import { chromium } from 'playwright';
import { mkdirSync } from 'node:fs';
const OUT = process.argv[2] ?? 'test/out/colors'; mkdirSync(OUT, { recursive: true });
const CLIP = process.env.CLIP ?? '/home/claude/sample15a.webm';
const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium-1243/chrome-linux64/chrome', args: ['--enable-unsafe-webgpu', '--use-webgpu-adapter=swiftshader', '--enable-features=Vulkan', '--use-vulkan=swiftshader', '--disable-vulkan-surface'] });
const page = await b.newPage({ viewport: { width: 1440, height: 1000 } });
page.on('pageerror', (e) => console.log('[pageerror]', e.message));
await page.addInitScript(() => { window.__pvHeadless = true; });
await page.goto('http://localhost:4173/'); await page.waitForTimeout(800);
await page.setInputFiles('.row-actions input[type=file]', 'samples/interstellar-take1.pvproj.json');
await page.waitForTimeout(600);
await page.setInputFiles('.file-card .actions input[type=file]', CLIP);
await page.waitForTimeout(1500);
await page.click('.stepper >> text=Style');
await page.waitForTimeout(800);
const look = () => page.evaluate(() => window.pianoverseProject.look ?? {});
const panel = (name) => page.screenshot({ path: `${OUT}/${name}`, clip: { x: 1140, y: 56, width: 300, height: 690 } });
await page.click('.layer-row >> text=Colours'); await page.waitForTimeout(300);
await page.click('.pal >> text=Synthwave'); await page.waitForTimeout(200);
await panel('1-colours-gradient.png');
await page.click('.by >> text=One colour'); await page.waitForTimeout(200);
const w = await page.$('.wheel'); const bb = await w.boundingBox();
await page.mouse.click(bb.x + bb.width * 0.8, bb.y + bb.height * 0.3); await page.waitForTimeout(200);
await panel('2-colours-wheel.png');
console.log('one colour:', JSON.stringify(await look()));
await page.click('.by >> text=Random'); await page.waitForTimeout(200);
await page.click('.layer-row >> text=Notes'); await page.waitForTimeout(300);
await page.evaluate(() => document.querySelector('.ctl-section:nth-of-type(3)')?.scrollIntoView());
await page.click('.seg button:text-is("2D")'); await page.waitForTimeout(200);
console.log('2d:', (await look()).noteDim);
await page.click('label:has-text("Note texture") input[type=checkbox]'); await page.waitForTimeout(200);
await page.click('.tex >> text=Onyx'); await page.waitForTimeout(300);
const l = await look(); console.log('onyx:', l.texOn, l.noteTexture, 'colorBy', l.colorBy);
await page.$eval('.tex-grid', (e) => e.scrollIntoView({ block: 'start' }));
await panel('3-notes-material.png');
await b.close();
