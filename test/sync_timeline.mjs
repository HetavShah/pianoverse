import { chromium } from 'playwright';
const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium-1243/chrome-linux64/chrome', args: ['--enable-unsafe-webgpu', '--use-webgpu-adapter=swiftshader', '--enable-features=Vulkan', '--use-vulkan=swiftshader', '--disable-vulkan-surface'] });
const page = await b.newPage({ viewport: { width: 1500, height: 950 } });
page.on('pageerror', (e) => console.log('[pageerror]', e.message));
await page.addInitScript(() => { window.__pvHeadless = true; });
await page.goto('http://localhost:4173/'); await page.waitForTimeout(800);
await page.setInputFiles('.start label.btn.primary input[type=file]', ['/home/claude/sample15a.webm', 'samples/interstellar-take1.pvproj.json']);
await page.waitForTimeout(1000);
await page.click('.modes >> text=Notes');
await page.setInputFiles('.calib-panel input[type=file]', 'test/fixtures/interstellar-shifted.mid');
await page.waitForFunction(() => window.pianoverseProject?.noteSource?.confidence !== undefined, null, { timeout: 60000 });
await page.$eval('.scrub', (el) => { const set = Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, 'value').set; set.call(el, '7'); el.dispatchEvent(new Event('input', { bubbles: true })); });
await page.waitForTimeout(800);
const score = () => page.$eval('.sync-head', (e) => e.querySelector('.score')?.textContent ?? 'none');
console.log('lined up:', await score());
await page.screenshot({ path: 'test/out/notes/t1-synced.png' });
for (let i = 0; i < 4; i++) await page.click('text=+1 fr');
await page.waitForTimeout(300);
console.log('4 frames late:', await score());
await page.locator('.sync-panel').screenshot({ path: 'test/out/notes/t2-late.png' });
// drag notes back 133 ms in the notes lane
const c = await page.$eval('.sync-canvas', (el) => { const r = el.getBoundingClientRect(); return { x: r.left, y: r.top, w: r.width, h: r.height }; });
const pxPerSec = (c.w - 64) / 8;
await page.mouse.move(c.x + c.w * 0.6, c.y + c.h * 0.8); await page.mouse.down();
await page.mouse.move(c.x + c.w * 0.6 - 0.133 * pxPerSec, c.y + c.h * 0.8, { steps: 6 });
console.log('while dragging back:', await score());
await page.locator('.sync-panel').screenshot({ path: 'test/out/notes/t3-dragging.png' });
await page.mouse.up();
console.log('after drag: offset', (await page.evaluate(() => window.pianoverseProject.noteSource.offset)).toFixed(3), await score());
await page.click('text=Whole video'); await page.waitForTimeout(200);
await page.locator('.sync-panel').screenshot({ path: 'test/out/notes/t4-whole.png' });
// resize taller
const hb = await page.$eval('.resize-handle', (el) => { const r = el.getBoundingClientRect(); return { x: r.left + r.width / 2, y: r.top + r.height / 2 }; });
await page.mouse.move(hb.x, hb.y); await page.mouse.down(); await page.mouse.move(hb.x, hb.y - 150, { steps: 5 }); await page.mouse.up();
await page.click('text=Follow playhead'); await page.waitForTimeout(200);
console.log('panel height after resize:', await page.$eval('.sync-panel', (e) => e.getBoundingClientRect().height));
await page.screenshot({ path: 'test/out/notes/t5-taller.png' });
await b.close();
